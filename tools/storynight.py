"""storynight.py <main>: which time zone each story select's race is run in -> src/storynight.h.

clEffStoryType's table (A(0x973a5c0), 0x158 bytes a select): the word at +0x10 is the select's night flag
(clEffStoryType's bool getter at A(0x857d0a4), handed to the story console; 1 night, 0 morning). Checked against the
game: chapters 101..105 (selects 100..104) run day, night, day, day, night.

Output: STORYNIGHT[select 0..111], 1 for a night race."""
from wmmtaddr import A  # the arcade addresses of the build being read
import os
import struct
import sys

d = open(sys.argv[1], "rb").read()
ph, n = struct.unpack_from("<I", d, 0x1c)[0], struct.unpack_from("<H", d, 0x2c)[0]
segs = [struct.unpack_from("<8I", d, ph + 32 * i) for i in range(n)]


def rd(va, size):
    for t, off, v, _, fs, *_ in segs:
        if t == 1 and v <= va < v + fs:
            return d[off + va - v:off + va - v + size]
    raise KeyError(hex(va))


flags = [1 if struct.unpack("<i", rd(A(0x973a5c0) + 0x158 * t + 0x10, 4))[0] else 0 for t in range(112)]
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "..", "src", "storynight.h"), "w") as o:
    o.write("/* Generated by tools/storynight.py from the arcade's clEffStoryType table: do not edit. */\n")
    o.write("#ifndef STORYNIGHT_H\n#define STORYNIGHT_H\n\n")
    o.write("/* by story select (get_story_index): 1 when its race runs at night, 0 in the morning (menu_state.zone) */\n")
    o.write("static const unsigned char STORYNIGHT[112] = {\n")
    for i in range(0, 112, 16):
        o.write("  " + ", ".join(str(f) for f in flags[i:i + 16]) + ",\n")
    o.write("};\n\n#endif\n")
print("written", sum(flags), "night of", len(flags))
