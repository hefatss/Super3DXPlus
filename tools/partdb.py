"""Read when each car shows its tuned exhaust and its roll cage out of `main` by running the arcade's own rule under the
unicorn emulator, and write src/partdb.h.

usage: partdb.py <main>   (WMMT_MAIN for tools/recomp/x86emu.py)

- clCarConstructParam::clCarConstructParam(clV386CardData const&, ...) (A(0x8943a80)) sets the construct param's muffler
  (+0x21c: clCarStyle::isTunedMufflerChange, A(0x86c7788)) and roll bar (+0x21e: isTunedRollCage, A(0x86c7be8)); both are
  IsTuned(clEffCarType const&, power, handling, part) (A(0x85689d0)): part 3 (the muffler) true from a power level, part 12
  (the roll cage) from a handling level (the tables at A(0x9736ae0), each row two thresholds, the second for the car whose
  nsCarParts::BNGCarIDGetFromCarModelID is 0x21, 100 meaning never). The levels are the card's tune power and handling
  (0..24 each: clCarStyle +0x15 and +0x16, or the FULL TUNE's setting).
- clCarModelData::constructBody then shows MUFFLER2 instead of MUFFLER1 for the muffler and ROLLBAR for the roll bar.

Output: PART_MUFFLER[CARDB_NPACKS], PART_ROLLCAGE[CARDB_NPACKS]: the least power / handling level that shows it (99 never), by
CARDB_PACKS.
"""
from wmmtaddr import A  # the arcade addresses of the build being read
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "recomp"))
os.environ["WMMT_MAIN"] = sys.argv[1]
from x86emu import Emu  # noqa: E402

IS_TUNED = None  # (the exported symbol of the build: _Z7IsTuned...)
MUFFLER, ROLLCAGE = 3, 12
SUSPENSION = 8  # (isTunedSuspesionKit)
CLEARTAIL, GOLDEMBLEM, SMOKE, MACH = 9, 11, 13, 14  # (the Celsior's: isTunedClearTail, isTunedGoldEnblem, isTunedGlassFullSmoke, isTunedMachSticker)

e = Emu(trace_unknown=False)
IS_TUNED = next(a for n, a in e.syms.items() if n.startswith("_Z7IsTunedRK12clEffCarType"))
cardb = open(os.path.join(HERE, "..", "src", "cardb.h")).read()
packs = re.findall(r'"([^"]+)"', cardb[cardb.index("CARDB_PACKS["):cardb.index("};", cardb.index("CARDB_PACKS["))])
cars = json.load(open(os.path.join(HERE, "cars.json")))
model_of = {}
for m in cars["makers"]:
    for car in m["cars"]:
        cols = car["colors"] if isinstance(car["colors"], list) else [car["colors"]]
        model_of.setdefault(car["folder"], cols[0]["model"])
        # a colour can belong to another trim's model (the Evos' white is the RS, the GC8's yellow and white the RA...): its own folder and
        # model id. The arcade asks IsTuned for the model the colour picked, so those packs get the same parts (they were left at "never")
        for c in cols:
            model_of.setdefault(c.get("folder", car["folder"]), c["model"])
ptr = e.alloc(16)


def least(model, part, handling_axis):
    e.w32(ptr, model)
    for lv in range(25):
        args = (ptr, 0, lv, part) if handling_axis else (ptr, lv, 0, part)
        if e.call(IS_TUNED, *args) & 0xFF:
            return lv
    return 99


mu, rc, ct, ge, sm, mc, sp, sh = [], [], [], [], [], [], [], []
for p in packs:
    model = model_of.get(p)
    if model is None:
        for l in (mu, rc, ct, ge, sm, mc, sp, sh):
            l.append(99)
        continue
    mu.append(least(model, MUFFLER, False))
    rc.append(least(model, ROLLCAGE, True))
    ct.append(least(model, CLEARTAIL, True))
    ge.append(least(model, GOLDEMBLEM, True))
    sm.append(least(model, SMOKE, True))
    mc.append(least(model, MACH, True))
    sp.append(least(model, SUSPENSION, False))
    sh.append(least(model, SUSPENSION, True))
lines = ["/* Generated by tools/partdb.py from the arcade's IsTuned rule: do not edit. */", "#ifndef PARTDB_H", "#define PARTDB_H", "",
         "/* by CARDB_PACKS: the least tune power level that shows the tuned exhaust (MUFFLER2) and the least handling level that",
         " * shows the roll cage (ROLLBAR), and the handling levels for the Celsior's clear tail lamps, gold emblem, smoked glass and Mach sticker, 99 never",
         " * (clCarStyle::isTunedMufflerChange, isTunedRollCage, isTunedClearTail, isTunedGoldEnblem, isTunedGlassFullSmoke, isTunedMachSticker) */"]
for name, vals in (("PART_SUSP_POWER", sp), ("PART_SUSP_HANDLING", sh), ("PART_MUFFLER", mu), ("PART_ROLLCAGE", rc), ("PART_CLEARTAIL", ct), ("PART_EMBLEM", ge), ("PART_SMOKE", sm), ("PART_MACH", mc)):
    lines.append("static const unsigned char %s[%d] = {" % (name, len(packs)))
    for i in range(0, len(vals), 16):
        lines.append("  " + ", ".join(str(v) for v in vals[i:i + 16]) + ",")
    lines.append("};")
# the body's drop with the suspension kit (data/car_height.lua: height, over the car's default; clCarModelData::constructBody moves the body node by it when
# clCarConstructParam +0x21f (isTunedSuspesionKit) is on), by CARDB_PACKS, in the models' units
txt = open(os.path.join(os.path.dirname(os.path.abspath(sys.argv[1])), "data", "car_height.lua"), encoding="utf-8", errors="replace").read()
drop = {m.group(1).lower(): float(m.group(3)) - float(m.group(2))
        for m in re.finditer(r'name\s*=\s*"([^"]+)"\s*,\s*default\s*=\s*([-\d.]+)\s*,\s*height\s*=\s*([-\d.]+)', txt)}
lines.append("")
lines.append("/* the body's drop with the suspension kit (car_height.lua), by CARDB_PACKS, model units (negative: down) */")
lines.append("static const float CAR_HEIGHT[%d] = {" % len(packs))
vals = [drop.get(pk.lower(), 0.0) for pk in packs]
for i in range(0, len(vals), 8):
    lines.append("  " + ", ".join("%.3ff" % v for v in vals[i:i + 8]) + ",")
lines.append("};")
lines += ["", "#endif", ""]
open(os.path.join(HERE, "..", "src", "partdb.h"), "w").write("\n".join(lines))
print("%d packs: exhaust from power %s, roll cage from handling %s" % (len(packs), sorted(set(mu)), sorted(set(rc))))
